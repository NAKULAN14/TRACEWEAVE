"""
TRACEWEAVE - Phase 14.2.4
Batch DNS -> IP Correlation + Provenance

Consumes DNS evidence from Phase 14.1 and creates
provenance-linked DOMAIN -> IP relationships.

No network access is performed.
"""

import json
import os
from typing import Any, Dict, List

from forensic_engine.infrastructure.ip_correlation import (
    create_ip_relationship,
)

from forensic_engine.infrastructure.ip_provenance import (
    add_relationship_provenance,
)


INPUT_PATH = os.path.join(
    "reports",
    "phase14",
    "dns_resolution",
    "dns_evidence.json",
)

OUTPUT_DIR = os.path.join(
    "reports",
    "phase14",
    "ip_correlation",
)

OUTPUT_PATH = os.path.join(
    OUTPUT_DIR,
    "dns_ip_relationships.json",
)


def load_dns_evidence(
    path: str,
) -> List[Dict[str, Any]]:
    """Load DNS evidence generated by Phase 14.1."""

    with open(
        path,
        "r",
        encoding="utf-8",
    ) as file:

        data = json.load(file)

    if not isinstance(data, list):
        raise ValueError(
            "Expected DNS evidence to be a list."
        )

    return data


def get_dns_evidence_id(
    dns_record: Dict[str, Any],
) -> str:
    """
    Extract a stable evidence identifier.

    Phase 14.1 preserves the original IOC record,
    so the first IOC ID is used as the evidence reference.
    """

    ioc = dns_record.get(
        "ioc",
        {}
    )

    evidence_id = ioc.get(
        "first_ioc_id"
    )

    if not evidence_id:
        evidence_id = ioc.get(
            "ioc_id"
        )

    if not evidence_id:
        raise ValueError(
            "DNS evidence has no identifiable evidence ID."
        )

    return evidence_id


def get_source_information(
    dns_record: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Extract original source information from the
    Phase 12 observation preserved inside the DNS record.
    """

    ioc = dns_record.get(
        "ioc",
        {}
    )

    observations = ioc.get(
        "observations",
        []
    )

    if not observations:
        return {
            "source_artifact": None,
            "source_location": None,
        }

    first_observation = observations[0]

    observation = first_observation.get(
        "observation",
        {}
    )

    evidence = observation.get(
        "evidence",
        {}
    )

    return {
        "source_artifact": evidence.get(
            "artifact"
        ),
        "source_location": evidence.get(
            "source_location"
        ),
    }


def correlate_dns_to_ip(
    dns_records: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """
    Convert DNS A/AAAA records into provenance-linked
    DOMAIN -> IP relationships.
    """

    relationships = []

    for dns_record in dns_records:

        dns_evidence = dns_record.get(
            "dns_evidence"
        )

        if not dns_evidence:
            continue

        domain = dns_evidence.get(
            "domain"
        )

        resolution = dns_evidence.get(
            "resolution",
            {}
        )

        if resolution.get(
            "status"
        ) != "RESOLVED":
            continue

        provenance = dns_evidence.get(
            "provenance",
            {}
        )

        provider = provenance.get(
            "provider"
        )

        evidence_id = get_dns_evidence_id(
            dns_record
        )

        source = get_source_information(
            dns_record
        )

        records = resolution.get(
            "records",
            []
        )

        for record in records:

            record_type = str(
                record.get(
                    "record_type",
                    ""
                )
            ).upper()

            if record_type not in {
                "A",
                "AAAA",
            }:
                continue

            value = record.get(
                "value"
            )

            if not value:
                continue

            relationship = (
                create_ip_relationship(
                    domain=domain,
                    ip_value=value,
                    record_type=record_type,
                    dns_provider=provider,
                )
            )

            relationship = (
                add_relationship_provenance(
                    relationship=relationship,
                    dns_evidence_id=evidence_id,
                    source_artifact=source[
                        "source_artifact"
                    ],
                    source_location=source[
                        "source_location"
                    ],
                )
            )

            relationships.append(
                relationship
            )

    return relationships


def main() -> None:

    os.makedirs(
        OUTPUT_DIR,
        exist_ok=True,
    )

    dns_records = load_dns_evidence(
        INPUT_PATH
    )

    relationships = (
        correlate_dns_to_ip(
            dns_records
        )
    )

    output = {
        "input": INPUT_PATH,

        "relationship_count":
            len(relationships),

        "network_access_performed":
            False,

        "relationships":
            relationships,
    }

    with open(
        OUTPUT_PATH,
        "w",
        encoding="utf-8",
    ) as file:

        json.dump(
            output,
            file,
            indent=2,
        )

    print(
        json.dumps(
            output,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()